"""Compact specs for the components that had no reference page yet.

Each spec becomes components/reference/<slug>.md in the same format as the hand-written pages:
Styles · Usage (Use / Not for) · Rules (Must / Should / Never + Because) · Accessibility ·
Edge cases · API · Tokens · Related.  Token values are read from tokens/tokens.css, never typed.
Imported by build_component_reference.py.
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
_CSS = (ROOT / "tokens" / "tokens.css").read_text(encoding="utf8")
TOKENS = {}
for name, val in re.findall(r"(--[a-z0-9_-]+)\s*:\s*([^;]+);", _CSS):
    TOKENS.setdefault(name, re.sub(r"\s+", " ", val.split("/*")[0]).strip())


def _tok(names):
    rows = []
    for n in names:
        v = TOKENS.get(n)
        if v is None:
            raise KeyError(f"unknown token {n}")
        rows.append(f"| `{n}` | {v} |")
    return "| Token | Value |\n|---|---|\n" + "\n".join(rows)


def spec(slug, title, group, summary, related, *, styles, use, notfor, rules, a11y, edge, api, tokens):
    fm = (f"---\ntitle: {json.dumps(title)}\nslug: {slug}\ngroup: {group}\n"
          f"summary: {json.dumps(summary, ensure_ascii=False)}\nrelated: [{', '.join(r.lower().replace(' ', '-') for r in related)}]\n---\n\n")
    out = [fm + f"# {title}\n\n{summary}\n"]
    out.append("## Styles\n" + "\n".join(f"- {s}" for s in styles))
    out.append("## Usage\n### Use\n" + "\n".join(f"- {u}" for u in use) +
               "\n### Not for\n" + "\n".join(f"- {n}" for n in notfor))
    out.append("## Rules\n" + "\n".join(f"- **{lvl}** {txt}" for lvl, txt in rules))
    out.append("## Accessibility\n" + "\n".join(f"- {a}" for a in a11y))
    out.append("## Edge cases\n| Scenario | Fix |\n|---|---|\n" + "\n".join(f"| {s} | {f} |" for s, f in edge))
    out.append("## API\n| Prop | Type | Default |\n|---|---|---|\n" +
               "\n".join(f"| `{p}` | `{t}` | {d} |" for p, t, d in api))
    out.append("## Tokens\n" + _tok(tokens))
    out.append("## Related\n" + " · ".join(related))
    return "\n\n".join(out) + "\n"


